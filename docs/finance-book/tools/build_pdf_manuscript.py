def clean_title(line):
    t = re.sub(r'^第\s*\d+\s*章\s*', '', line).strip()
    t = re.split(r'一句话先说透|项目目标|目标：|目标:', t)[0].strip(' ：:')
    t = re.sub(r'\s+', ' ', t)
    return t[:42]

def clean_body(n, body):
    body = re.sub(r'^第\s*\d+\s*章\s*[^\n]+', '', body).strip()
    body = body.replace('PV=FV (1+r)n', 'PV = FV / (1+r)^n')
    body = body.replace('1+rreal=1+rnominal 1+π', '1+r_real = (1+r_nominal)/(1+π)')
    body = body.replace('cp.CLARA BEL', 'cp.CLARABEL')
    # Remove section numbering tokens from body but do not use them as headings; this avoids 0.001/1.94 becoming h2.
    body = re.sub(rf'(?<![\d.]){n}\.\d{{1,2}}\s+', ' ', body)
    body = re.sub(r'\s+', ' ', body)
    return body.strip()

def split_paragraphs(s, max_len=360):
    s = clean_body(0, s) if False else s.strip()
    # split mostly by Chinese punctuation and bullet marks; keep formulas as prose.
    raw_parts = re.split(r'(?<=[。；！？])\s+|\s*•\s*|\n+', s)
    parts = []
    for part in raw_parts:
        part = part.strip()
        if len(part) < 8:
            continue
        while len(part) > max_len:
            cut = max(part.rfind('。', 0, max_len), part.rfind('；', 0, max_len), part.rfind('，', 0, max_len))
            if cut < 120:
                cut = max_len
            parts.append(part[:cut+1].strip())
            part = part[cut+1:].strip()
        if part:
            parts.append(part)
    return parts

def html_paras(paras):
    return ''.join('<p>%s</p>' % p.replace('"', '&quot;') for p in paras if p.strip())

def group_paras(paras, size=4):
    return [paras[i:i+size] for i in range(0, len(paras), size)]

